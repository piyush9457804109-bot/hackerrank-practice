import java.util.*;

public class Solution {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        long r = sc.nextLong();
        
        long area = 3 * r * r;
        long perimeter = 2 * 3 * r;
        
        System.out.println(area);
        System.out.println(perimeter);
    }
}
